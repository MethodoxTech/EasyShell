using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace EasyShell.Generators
{
    /// <summary>
    /// Writes the curated libraries an assembly declares with <c>[assembly: ShellBindType(typeof(T), Library = "...")]</c>.
    /// </summary>
    /// <remarks>
    /// <para>For each library it writes a static property on an internal <c>ShellBindings</c> class, in a namespace named after the assembly, that builds a <c>CuratedLibrary</c> of the declared types. Each member is registered under the names reflection's public lookup would find it by, with a lambda that calls it directly - so the reflective binder and this one see the same candidates in the same order, and only the way the chosen one is called differs.</para>
    ///
    /// <para>The walk is reflection's: a type's own public static fields, properties and methods (not its bases', as <c>BindingFlags.Static</c> without <c>FlattenHierarchy</c>), and its public instance members together with those it inherits. A member that cannot be called without reflection is left out and listed in a comment in the generated file, with the reason.</para>
    /// </remarks>
    [Generator(LanguageNames.CSharp)]
    public sealed class ShellBindingGenerator : IIncrementalGenerator
    {
        private const string AttributeName = "EasyShell.Binding.ShellBindTypeAttribute";

        public void Initialize(IncrementalGeneratorInitializationContext context)
            => context.RegisterSourceOutput(context.CompilationProvider, static (production, compilation) => Execute(production, compilation));

        private sealed class Declaration
        {
            public INamedTypeSymbol Type = null!;
            public string Library = "Standard";
            public HashSet<string>? Include;
            public HashSet<string> Exclude = new(StringComparer.OrdinalIgnoreCase);
            public bool StaticOnly;
        }

        private static void Execute(SourceProductionContext production, Compilation compilation)
        {
            INamedTypeSymbol? attribute = compilation.GetTypeByMetadataName(AttributeName);
            if (attribute is null)
                return;

            List<Declaration> declarations = [];
            foreach (AttributeData data in compilation.Assembly.GetAttributes())
            {
                if (!SymbolEqualityComparer.Default.Equals(data.AttributeClass, attribute) || data.ConstructorArguments.Length != 1
                    || data.ConstructorArguments[0].Value is not INamedTypeSymbol type)
                    continue;

                Declaration declaration = new() { Type = type };
                foreach (KeyValuePair<string, TypedConstant> named in data.NamedArguments)
                {
                    switch (named.Key)
                    {
                        case "Library" when named.Value.Value is string library:
                            declaration.Library = library;
                            break;
                        case "Include" when !named.Value.IsNull:
                            declaration.Include = new HashSet<string>(named.Value.Values.Select(v => (string)v.Value!), StringComparer.OrdinalIgnoreCase);
                            break;
                        case "Exclude" when !named.Value.IsNull:
                            declaration.Exclude.UnionWith(named.Value.Values.Select(v => (string)v.Value!));
                            break;
                        case "StaticOnly" when named.Value.Value is bool staticOnly:
                            declaration.StaticOnly = staticOnly;
                            break;
                    }
                }
                declarations.Add(declaration);
            }
            if (declarations.Count == 0)
                return;

            string ns = SanitizeNamespace(compilation.AssemblyName ?? "EasyShellBindings");
            StringBuilder source = new();
            source.AppendLine("// <auto-generated/>");
            source.AppendLine("// Written by EasyShell.Generators from this assembly's [assembly: ShellBindType] declarations.");
            source.AppendLine("#nullable disable");
            source.AppendLine("#pragma warning disable");
            source.AppendLine($"namespace {ns}");
            source.AppendLine("{");
            source.AppendLine("    using global::EasyShell.Binding;");
            source.AppendLine();
            source.AppendLine("    internal static partial class ShellBindings");
            source.AppendLine("    {");
            source.AppendLine("        /// <summary>A converted argument as its parameter's type; null is the type's default, as reflection passes a missing value-type default.</summary>");
            source.AppendLine("        private static T Arg<T>(object[] a, int i) => a[i] is null ? default : (T)a[i];");
            source.AppendLine();

            List<string> libraries = [.. declarations.Select(d => d.Library).Distinct()];
            int index = 0;
            StringBuilder binders = new();
            foreach (string library in libraries)
            {
                List<string> methods = [];
                foreach (Declaration declaration in declarations.Where(d => d.Library == library))
                {
                    string method = $"Bind{index++}_{Identifier(declaration.Type.Name)}";
                    methods.Add(method);
                    EmitType(binders, method, declaration);
                }

                string field = "_" + Identifier(library);
                source.AppendLine($"        /// <summary>The {library} library: {string.Join(", ", declarations.Where(d => d.Library == library).Select(d => MetadataFullName(d.Type)))}.</summary>");
                source.AppendLine($"        public static CuratedLibrary {Identifier(library)} => {field} ??= new CuratedLibrary(\"{library}\")");
                foreach (string method in methods)
                    source.AppendLine($"            .Add({method}())");
                source.AppendLine("            ;");
                source.AppendLine($"        private static CuratedLibrary {field};");
                source.AppendLine();
            }
            source.Append(binders);
            source.AppendLine("    }");
            source.AppendLine("}");

            production.AddSource("ShellBindings.g.cs", source.ToString());
        }

        #region Members
        private static void EmitType(StringBuilder output, string method, Declaration declaration)
        {
            INamedTypeSymbol type = declaration.Type;
            string typeName = TypeName(type);
            List<string> skipped = [];

            output.AppendLine($"        private static CuratedType {method}()");
            output.AppendLine("        {");
            output.AppendLine($"            CuratedType t = new(\"{MetadataFullName(type)}\", typeof({typeName}));");

            // Statics: the type's own declarations only.
            foreach (ISymbol member in type.GetMembers())
                if (member.IsStatic && member.DeclaredAccessibility == Accessibility.Public && Wanted(declaration, member.Name))
                    EmitMember(output, member, isStatic: true, skipped);

            // Instance members: the type's and every base's, most derived first, an override or a hidden signature only once.
            if (!declaration.StaticOnly && !type.IsStatic && !type.IsRefLikeType)
            {
                HashSet<string> seen = new(StringComparer.Ordinal);
                for (INamedTypeSymbol? current = type; current is not null; current = current.BaseType)
                {
                    foreach (ISymbol member in current.GetMembers())
                    {
                        if (member.IsStatic || member.DeclaredAccessibility != Accessibility.Public || !Wanted(declaration, member.Name))
                            continue;
                        if (member is IMethodSymbol m && !seen.Add(Signature(m)))
                            continue;
                        EmitMember(output, member, isStatic: false, skipped, receiverType: type);
                    }
                }
            }

            output.AppendLine("            return t;");
            foreach (string reason in skipped)
                output.AppendLine($"            // Not bound: {reason}");
            output.AppendLine("        }");
            output.AppendLine();
        }

        private static bool Wanted(Declaration declaration, string name)
            => name != "GetType"
            && (declaration.Include is null || declaration.Include.Contains(name) || declaration.Include.Contains(StripAccessor(name)))
            && !declaration.Exclude.Contains(name) && !declaration.Exclude.Contains(StripAccessor(name));

        private static string StripAccessor(string name)
            => name.StartsWith("get_", StringComparison.Ordinal) || name.StartsWith("set_", StringComparison.Ordinal) ? name.Substring(4) : name;

        private static void EmitMember(StringBuilder output, ISymbol member, bool isStatic, List<string> skipped, INamedTypeSymbol? receiverType = null)
        {
            string staticText = isStatic ? "true" : "false";
            if (Refusal(member) is string refused)
            {
                skipped.Add($"{member.ContainingType.Name}.{member.Name} - {refused}");
                return;
            }

            switch (member)
            {
                case IFieldSymbol field:
                    if (!IsUsableType(field.Type))
                    {
                        skipped.Add($"{field.Name} - its type cannot be boxed");
                        return;
                    }
                    output.AppendLine($"            t.Field({staticText}, \"{field.Name}\", static r => {Receiver(field, isStatic)}.{Escape(field.Name)});");
                    return;

                case IPropertySymbol property:
                    if (property.IsIndexer || property.GetMethod is null || property.GetMethod.DeclaredAccessibility != Accessibility.Public)
                        return;
                    if (!IsUsableType(property.Type))
                    {
                        skipped.Add($"{property.Name} - its type cannot be boxed");
                        return;
                    }
                    output.AppendLine($"            t.Property({staticText}, \"{property.Name}\", static r => {Receiver(property, isStatic)}.{Escape(property.Name)});");
                    return;

                case IMethodSymbol method:
                    EmitMethod(output, method, staticText, isStatic, skipped);
                    return;
            }
        }

        private static void EmitMethod(StringBuilder output, IMethodSymbol method, string staticText, bool isStatic, List<string> skipped)
        {
            if (method.MethodKind is not (MethodKind.Ordinary or MethodKind.PropertyGet or MethodKind.PropertySet))
                return;   // constructors, operators, conversions and event accessors: reflection's binder never offered a way to reach them usefully
            if (method.IsGenericMethod)
            {
                skipped.Add($"{method.Name} - generic; NativeAOT cannot close a generic at run time");
                return;
            }
            if (method.ReturnsByRef || method.ReturnsByRefReadonly || (!method.ReturnsVoid && !IsUsableType(method.ReturnType)))
            {
                skipped.Add($"{Signature(method)} - its result cannot be boxed");
                return;
            }
            foreach (IParameterSymbol p in method.Parameters)
            {
                if (p.RefKind != RefKind.None || !IsUsableType(p.Type))
                {
                    skipped.Add($"{Signature(method)} - parameter '{p.Name}' cannot be passed as an object");
                    return;
                }
            }

            IPropertySymbol? property = method.AssociatedSymbol as IPropertySymbol;
            if (method.MethodKind == MethodKind.PropertySet && (method.IsInitOnly || (!isStatic && method.ContainingType.IsValueType)))
                return;   // a copy's property cannot be assigned, and an init accessor is construction

            StringBuilder parameters = new();
            StringBuilder arguments = new();
            for (int i = 0; i < method.Parameters.Length; i++)
            {
                IParameterSymbol p = method.Parameters[i];
                if (i > 0) { parameters.Append(", "); arguments.Append(", "); }
                string pType = TypeName(p.Type);
                parameters.Append(p.HasExplicitDefaultValue
                    ? $"new ShellParameter(typeof({pType}), true, {DefaultLiteral(p)})"
                    : $"new ShellParameter(typeof({pType}))");
                arguments.Append($"Arg<{pType}>(a, {i})");
            }

            string receiver = Receiver(method, isStatic);
            string call;
            bool isVoid = method.ReturnsVoid;
            if (property is not null && method.MethodKind == MethodKind.PropertyGet)
                call = property.IsIndexer ? $"{receiver}[{arguments}]" : $"{receiver}.{Escape(property.Name)}";
            else if (property is not null && method.MethodKind == MethodKind.PropertySet)
            {
                string[] parts = SplitArguments(method.Parameters.Length);
                string target = property.IsIndexer ? $"{receiver}[{string.Join(", ", parts.Take(parts.Length - 1))}]" : $"{receiver}.{Escape(property.Name)}";
                call = $"{target} = {parts[parts.Length - 1]}";
                isVoid = true;
            }
            else
                call = $"{receiver}.{Escape(method.Name)}({arguments})";

            string body = isVoid ? $"{{ {call}; return null; }}" : call;

            string paramsTail = string.Empty;
            IParameterSymbol? last = method.Parameters.LastOrDefault();
            if (last is not null && last.IsParams && last.Type is IArrayTypeSymbol { Rank: 1 } array)
            {
                if (array.ElementType is IArrayTypeSymbol)
                {
                    skipped.Add($"{Signature(method)} - a params array of arrays");
                    return;
                }
                string element = TypeName(array.ElementType);
                paramsTail = $", typeof({element}), static n => new {element}[n]";
            }

            output.AppendLine($"            t.Method({staticText}, new ShellMethod(\"{method.Name}\", [{parameters}], static (r, a) => {body}{paramsTail}));");

            string[] SplitArguments(int count)
                => [.. Enumerable.Range(0, count).Select(i => $"Arg<{TypeName(method.Parameters[i].Type)}>(a, {i})")];
        }

        /// <summary>The receiver as the member's declaring type: a static type name, or the boxed target cast to the type that declares the member, so the call binds to exactly that member and still dispatches virtually.</summary>
        private static string Receiver(ISymbol member, bool isStatic)
            => isStatic ? TypeName(member.ContainingType) : $"(({TypeName(member.ContainingType)})r)";

        /// <summary>Why a member must not be bound, from its own attributes or its property's.</summary>
        private static string? Refusal(ISymbol member)
        {
            IEnumerable<AttributeData> attributes = member.GetAttributes();
            if (member is IMethodSymbol { AssociatedSymbol: IPropertySymbol owner })
                attributes = attributes.Concat(owner.GetAttributes());
            foreach (AttributeData attribute in attributes)
            {
                switch (attribute.AttributeClass?.Name)
                {
                    case "RequiresUnreferencedCodeAttribute":
                    case "RequiresDynamicCodeAttribute":
                    case "RequiresAssemblyFilesAttribute":
                        return "it requires " + attribute.AttributeClass.Name.Replace("Requires", string.Empty).Replace("Attribute", string.Empty);
                    case "ObsoleteAttribute":
                        return "obsolete";
                    case "ExperimentalAttribute":
                    case "RequiresPreviewFeaturesAttribute":
                        return "experimental";
                }
            }
            return null;
        }
        #endregion

        #region Types and literals
        /// <summary>Whether a value of the type can travel as an object and be named in generated code.</summary>
        private static bool IsUsableType(ITypeSymbol type)
        {
            switch (type)
            {
                case IArrayTypeSymbol array:
                    return IsUsableType(array.ElementType);
                case INamedTypeSymbol named:
                    if (named.IsRefLikeType)
                        return false;
                    for (INamedTypeSymbol? t = named; t is not null; t = t.ContainingType)
                        if (t.DeclaredAccessibility != Accessibility.Public)
                            return false;
                    return named.TypeArguments.All(IsUsableType);
                default:
                    return false;   // pointers, function pointers, type parameters, dynamic
            }
        }

        private static string DefaultLiteral(IParameterSymbol p)
        {
            object? value = p.ExplicitDefaultValue;
            if (value is null)
                return "null";

            ITypeSymbol type = p.Type;
            if (type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } nullable)
                type = nullable.TypeArguments[0];
            return $"({TypeName(type)})({Literal(value)})";
        }

        private static string Literal(object value) => value switch
        {
            string s => SymbolDisplay.FormatLiteral(s, quote: true),
            char c => SymbolDisplay.FormatLiteral(c, quote: true),
            bool b => b ? "true" : "false",
            double d when double.IsNaN(d) => "double.NaN",
            double d when double.IsPositiveInfinity(d) => "double.PositiveInfinity",
            double d when double.IsNegativeInfinity(d) => "double.NegativeInfinity",
            double d => d.ToString("R", CultureInfo.InvariantCulture) + "D",
            float f when float.IsNaN(f) => "float.NaN",
            float f when float.IsPositiveInfinity(f) => "float.PositiveInfinity",
            float f when float.IsNegativeInfinity(f) => "float.NegativeInfinity",
            float f => f.ToString("R", CultureInfo.InvariantCulture) + "F",
            decimal m => m.ToString(CultureInfo.InvariantCulture) + "M",
            long l => l.ToString(CultureInfo.InvariantCulture) + "L",
            ulong ul => ul.ToString(CultureInfo.InvariantCulture) + "UL",
            uint ui => ui.ToString(CultureInfo.InvariantCulture) + "U",
            IFormattable f => f.ToString(null, CultureInfo.InvariantCulture),
            _ => value.ToString() ?? "null",
        };

        private static string TypeName(ITypeSymbol type)
            => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        /// <summary>The name a script writes and reflection's <c>Type.FullName</c> gives: namespace, then nested types joined by '+'.</summary>
        private static string MetadataFullName(INamedTypeSymbol type)
        {
            string name = type.MetadataName;
            for (INamedTypeSymbol? outer = type.ContainingType; outer is not null; outer = outer.ContainingType)
                name = outer.MetadataName + "+" + name;
            string ns = type.ContainingNamespace is { IsGlobalNamespace: false } containing ? containing.ToDisplayString() + "." : string.Empty;
            return ns + name;
        }

        private static string Signature(IMethodSymbol method)
            => method.Name + "(" + string.Join(",", method.Parameters.Select(p => p.RefKind + " " + TypeName(p.Type))) + ")";

        private static string Escape(string name)
            => SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;

        private static string Identifier(string text)
        {
            StringBuilder builder = new();
            foreach (char c in text)
                builder.Append(char.IsLetterOrDigit(c) ? c : '_');
            if (builder.Length == 0 || char.IsDigit(builder[0]))
                builder.Insert(0, '_');
            return builder.ToString();
        }

        private static string SanitizeNamespace(string assemblyName)
            => string.Join(".", assemblyName.Split('.').Select(Identifier));
        #endregion
    }
}
